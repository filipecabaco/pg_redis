# Writes sql/views.sql: one view per type, and redis.keys, over all sixteen databases' tables.
# Each view unions the sixteen tables of its type with a `db` column; PostgreSQL drops the
# branches a `db = n` filter excludes, so a query on one database reads only its tables.
#
#   elixir sql/gen_views.exs

dbs = 0..15

union = fn f -> Enum.map_join(dbs, "\nUNION ALL\n", f) end

# A key is live while it has no deadline or the deadline is ahead, as Redis
# sees it: the expiry sweep may not have reached one that has passed.
live = "(e.expires_at IS NULL OR e.expires_at > now())"

strings =
  union.(fn n ->
    "SELECT #{n} AS db, redis.text(t.key) AS key, redis.text(t.value) AS value, " <>
      "t.key AS key_bytes, t.value AS value_bytes, t.expires_at\n" <>
      "  FROM redis.kv_#{n} t WHERE t.expires_at IS NULL OR t.expires_at > now()"
  end)

collection = fn table, cols ->
  union.(fn n ->
    "SELECT #{n} AS db, redis.text(t.key) AS key, #{cols}, t.key AS key_bytes, e.expires_at\n" <>
      "  FROM redis.#{table}_#{n} t LEFT JOIN redis.expiry_#{n} e ON e.key = t.key WHERE #{live}"
  end)
end

hashes =
  collection.(
    "hash",
    "redis.text(t.field) AS field, redis.text(t.value) AS value, t.field AS field_bytes, t.value AS value_bytes, t.seq"
  )

# A list's position is numbered in a subquery, so the `db` column stays outside the window
# and a filter on it still drops the other databases' branches.
lists =
  union.(fn n ->
    "SELECT #{n} AS db, redis.text(l.key) AS key, l.position, redis.text(l.value) AS value, " <>
      "l.value AS value_bytes, l.key AS key_bytes, l.expires_at\n" <>
      "  FROM (SELECT t.key, t.value, e.expires_at, " <>
      "(row_number() OVER (PARTITION BY t.key ORDER BY t.pos) - 1)::bigint AS position\n" <>
      "          FROM redis.list_#{n} t LEFT JOIN redis.expiry_#{n} e ON e.key = t.key WHERE #{live}) l"
  end)

sets = collection.("set", "redis.text(t.member) AS member, t.member AS member_bytes, t.seq")

zsets =
  collection.(
    "zset",
    "redis.text(t.member) AS member, t.score, t.member AS member_bytes"
  )

streams =
  union.(fn n ->
    "SELECT #{n} AS db, redis.text(t.key) AS key, t.key AS key_bytes, e.expires_at\n" <>
      "  FROM redis.stream_#{n} t LEFT JOIN redis.expiry_#{n} e ON e.key = t.key WHERE #{live}"
  end)

# A value as jsonb: its text when it is UTF-8, otherwise {"base64": ...}.
j = fn col -> "COALESCE(to_jsonb(redis.text(#{col})), jsonb_build_object('base64', encode(#{col}, 'base64')))" end

sql = """
-- Generated by sql/gen_views.exs: edit that, then run `elixir sql/gen_views.exs`.
--
-- The data in tables, by type, across every database: one view for each type, with the
-- database as a column, keys and values as text (NULL where the bytes are not UTF-8; the
-- `*_bytes` columns hold them exactly), and only keys that are live: an expired key is gone
-- for Redis, so it is gone here. `redis.keys` is every key with its whole value as jsonb.
--
-- These read what is in tables: the logged databases, and any database while it is moving
-- into them. A memory database lives in shared memory; `redis.memory_keys(db)` reads it.
-- Filter on `key_bytes` (`key_bytes = 'session:9f2c'`) for an indexed lookup of one key.

CREATE OR REPLACE VIEW redis.strings AS
#{strings};

CREATE OR REPLACE VIEW redis.hashes AS
#{hashes};

CREATE OR REPLACE VIEW redis.lists AS
#{lists};

CREATE OR REPLACE VIEW redis.sets AS
#{sets};

CREATE OR REPLACE VIEW redis.zsets AS
#{zsets};

CREATE OR REPLACE VIEW redis.streams AS
#{streams};

-- Every key once: its type, and its value as jsonb. A string is a JSON string, a hash an
-- object, a list an array, a set an array in insertion order, a sorted set
-- an array of [member, score] by score. Bytes that are not UTF-8 are {"base64": ...}. A
-- stream's entries are not decoded: its value is NULL.
CREATE OR REPLACE VIEW redis.keys AS
SELECT db, key, 'string' AS type, #{j.("value_bytes")} AS value, key_bytes, expires_at
  FROM redis.strings
UNION ALL
SELECT db, min(key), 'hash', jsonb_object_agg(COALESCE(field, encode(field_bytes, 'base64')), #{j.("value_bytes")} ORDER BY seq),
       key_bytes, min(expires_at)
  FROM redis.hashes GROUP BY db, key_bytes
UNION ALL
SELECT db, min(key), 'list', jsonb_agg(#{j.("value_bytes")} ORDER BY position), key_bytes, min(expires_at)
  FROM redis.lists GROUP BY db, key_bytes
UNION ALL
SELECT db, min(key), 'set', jsonb_agg(#{j.("member_bytes")} ORDER BY seq), key_bytes, min(expires_at)
  FROM redis.sets GROUP BY db, key_bytes
UNION ALL
SELECT db, min(key), 'zset', jsonb_agg(jsonb_build_array(#{j.("member_bytes")}, score) ORDER BY score, member_bytes),
       key_bytes, min(expires_at)
  FROM redis.zsets GROUP BY db, key_bytes
UNION ALL
SELECT db, key, 'stream', NULL::jsonb, key_bytes, expires_at
  FROM redis.streams;

-- A memory database's keys, in the shape of redis.keys, from redis.memory_entries: shared
-- memory has no tables to put a view on. A function, so it reads only the database asked
-- for; a whole database is read, in pages.
CREATE OR REPLACE FUNCTION redis.memory_keys(db int)
RETURNS TABLE (db int, key text, type text, value jsonb, key_bytes bytea, expires_at timestamptz)
LANGUAGE sql STABLE AS $$
  SELECT $1, redis.text(m.k), m.t,
         CASE m.t
           WHEN 'string' THEN (array_agg(#{j.("m.v")}))[1]
           WHEN 'hash' THEN jsonb_object_agg(COALESCE(redis.text(m.f), encode(m.f, 'base64')), #{j.("m.v")} ORDER BY m.pos)
                                FILTER (WHERE m.t = 'hash')
           WHEN 'zset' THEN jsonb_agg(jsonb_build_array(#{j.("m.v")}, convert_from(m.f, 'UTF8')::float8) ORDER BY m.pos)
                                FILTER (WHERE m.t = 'zset')
           WHEN 'stream' THEN NULL
           ELSE jsonb_agg(#{j.("m.v")} ORDER BY m.pos)
         END,
         m.k, to_timestamp(min(d.us) / 1e6)
    FROM redis.memory_entries($1) WITH ORDINALITY AS m(k, t, f, v, pos)
    LEFT JOIN redis.memory_deadlines($1) AS d(k, us) ON d.k = m.k
   GROUP BY m.k, m.t
$$;
"""

File.write!(Path.join(__DIR__, "views.sql"), sql)
IO.puts("wrote sql/views.sql (#{byte_size(sql)} bytes)")
