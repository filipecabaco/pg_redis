#!/usr/bin/env elixir
# Generates src/redis_tables.rs from a Redis source tree: the command table
# (src/commands/*.json — arity, flags, key specs, docs) behind COMMAND INFO,
# DOCS, LIST and GETKEYS, and the config table (src/config.c) behind CONFIG
# GET/SET. Defaults come from a real server, rendered exactly as CONFIG GET
# prints them, so nothing here re-derives Redis's formatting rules.
#
#   elixir scripts/gen_redis_tables.exs --redis-src path/to/redis-7.2.5 \
#          --config-defaults scripts/redis-7.2-config-defaults.txt > src/redis_tables.rs
#
# The defaults file is `CONFIG GET '*'` from a fresh redis:7.2-alpine, plus a
# `CONFIG GET <name>` for each hidden config, which `*` leaves out; blank
# lines are dropped from the hidden part only (in the `*` part they are real
# empty values).
#
# No dependencies: JSON and regexes are built in.

defmodule Gen do
  def run(argv) do
    {opts, _} =
      OptionParser.parse!(argv, strict: [redis_src: :string, config_defaults: :string])

    src = Keyword.fetch!(opts, :redis_src)
    defaults = Keyword.fetch!(opts, :config_defaults) |> read_defaults()

    IO.puts(header())
    IO.puts(commands(Path.join(src, "src/commands")))
    IO.puts(configs(Path.join(src, "src/config.c"), defaults))
  end

  defp header do
    """
    // @generated by scripts/gen_redis_tables.exs from the Redis 7.2.5 sources.
    // Do not edit by hand: regenerate instead.

    pub struct KeySpec {
        pub notes: &'static str,
        pub flags: &'static [&'static str],
        pub begin: Begin,
        pub find: Find,
    }

    pub enum Begin {
        Index(i32),
        Keyword(&'static str, i32),
        Unknown,
    }

    pub enum Find {
        Range { lastkey: i32, step: i32, limit: i32 },
        Keynum { keynumidx: i32, firstkey: i32, step: i32 },
        Unknown,
    }

    pub struct Arg {
        pub name: &'static str,
        pub kind: &'static str,
        pub token: &'static str,
        pub display: &'static str,
        pub key_spec_index: i32,
        pub optional: bool,
        pub multiple: bool,
        pub multiple_token: bool,
        pub since: &'static str,
        pub summary: &'static str,
        pub deprecated_since: &'static str,
        pub args: &'static [Arg],
    }

    pub struct CommandSpec {
        /// Lowercase; a subcommand is `container|name`, as COMMAND INFO spells it.
        pub name: &'static str,
        pub container: &'static str,
        pub arity: i32,
        pub flags: &'static [&'static str],
        pub acl_categories: &'static [&'static str],
        pub key_specs: &'static [KeySpec],
        pub group: &'static str,
        pub since: &'static str,
        pub summary: &'static str,
        pub complexity: &'static str,
        pub tips: &'static [&'static str],
        pub doc_flags: &'static [&'static str],
        pub deprecated_since: &'static str,
        pub replaced_by: &'static str,
        pub history: &'static [(&'static str, &'static str)],
        pub args: &'static [Arg],
    }

    pub enum ConfigKind {
        Bool,
        Int { min: i128, max: i128, memory: bool, percent: bool, octal: bool },
        Enum { choices: &'static [&'static str], multi: bool },
        Str,
        Special,
    }

    pub struct ConfigSpec {
        pub name: &'static str,
        pub alias: &'static str,
        pub immutable: bool,
        pub hidden: bool,
        pub protected: bool,
        pub kind: ConfigKind,
        /// What CONFIG GET prints on a fresh Redis 7.2.
        pub default: &'static str,
    }
    """
  end

  # ─────────────────────────────── commands ───────────────────────────────

  defp commands(dir) do
    specs =
      dir
      |> File.ls!()
      |> Enum.filter(&String.ends_with?(&1, ".json"))
      |> Enum.sort()
      |> Enum.flat_map(fn f ->
        dir |> Path.join(f) |> File.read!() |> JSON.decode!() |> Map.to_list()
      end)
      |> Enum.map(fn {name, c} -> command(name, c) end)
      |> Enum.sort()

    "pub static COMMANDS: &[CommandSpec] = &[\n" <> Enum.join(specs, "") <> "];\n"
  end

  defp command(name, c) do
    full =
      case c["container"] do
        nil -> String.downcase(name)
        k -> String.downcase(k) <> "|" <> String.downcase(name)
      end

    """
        CommandSpec {
            name: #{s(full)},
            container: #{s(String.downcase(c["container"] || ""))},
            arity: #{c["arity"]},
            flags: #{strs(Enum.map(c["command_flags"] || [], &String.downcase/1))},
            acl_categories: #{strs(Enum.map(c["acl_categories"] || [], &String.downcase/1))},
            key_specs: &[#{Enum.map_join(c["key_specs"] || [], ", ", &key_spec/1)}],
            group: #{s(c["group"] || "")},
            since: #{s(c["since"] || "")},
            summary: #{s(c["summary"] || "")},
            complexity: #{s(c["complexity"] || "")},
            tips: #{strs(Enum.map(c["command_tips"] || [], &String.downcase/1))},
            doc_flags: #{strs(Enum.map(c["doc_flags"] || [], &String.downcase/1))},
            deprecated_since: #{s(c["deprecated_since"] || "")},
            replaced_by: #{s(c["replaced_by"] || "")},
            history: &[#{Enum.map_join(c["history"] || [], ", ", fn [v, d] -> "(#{s(v)}, #{s(d)})" end)}],
            args: #{args(c["arguments"] || [])},
        },
    """
  end

  defp key_spec(k) do
    begin =
      case k["begin_search"] do
        %{"index" => %{"pos" => p}} -> "Begin::Index(#{p})"
        %{"keyword" => %{"keyword" => kw, "startfrom" => f}} -> "Begin::Keyword(#{s(kw)}, #{f})"
        _ -> "Begin::Unknown"
      end

    find =
      case k["find_keys"] do
        %{"range" => r} ->
          "Find::Range { lastkey: #{r["lastkey"]}, step: #{r["step"]}, limit: #{r["limit"]} }"

        %{"keynum" => n} ->
          "Find::Keynum { keynumidx: #{n["keynumidx"]}, firstkey: #{n["firstkey"]}, step: #{n["step"]} }"

        _ ->
          "Find::Unknown"
      end

    "KeySpec { notes: #{s(k["notes"] || "")}, flags: #{strs(k["flags"] || [])}, begin: #{begin}, find: #{find} }"
  end

  defp args([]), do: "&[]"

  defp args(list) do
    "&[" <>
      Enum.map_join(list, ", ", fn a ->
        "Arg { name: #{s(a["name"])}, kind: #{s(a["type"])}, token: #{s(a["token"] || "")}, " <>
          "display: #{s(a["display"] || "")}, key_spec_index: #{Map.get(a, "key_spec_index", -1)}, " <>
          "optional: #{a["optional"] == true}, multiple: #{a["multiple"] == true}, " <>
          "multiple_token: #{a["multiple_token"] == true}, since: #{s(a["since"] || "")}, " <>
          "summary: #{s(a["summary"] || "")}, deprecated_since: #{s(a["deprecated_since"] || "")}, " <>
          "args: #{args(a["arguments"] || [])} }"
      end) <> "]"
  end

  # ──────────────────────────────── config ────────────────────────────────

  defp read_defaults(path) do
    path
    |> File.read!()
    |> String.split("\n")
    |> Enum.chunk_every(2, 2, :discard)
    |> Map.new(fn [k, v] -> {k, v} end)
  end

  defp configs(path, defaults) do
    text = File.read!(path)
    enums = enums(text)

    [_, table] = String.split(text, "standardConfig static_configs[] = {", parts: 2)
    [table | _] = String.split(table, "\n};", parts: 2)

    entries =
      Regex.scan(~r/create(\w+)Config\((.*)\),?\s*(?:\/\*.*)?$/m, table)
      |> Enum.map(fn [_, kind, rest] -> config(kind, split_args(rest), enums, defaults) end)
      |> Enum.reject(&is_nil/1)

    "pub static CONFIGS: &[ConfigSpec] = &[\n" <> Enum.join(entries, "") <> "];\n"
  end

  defp enums(text) do
    Regex.scan(~r/configEnum (\w+)\[\] = \{(.*?)\};/s, text)
    |> Map.new(fn [_, name, body] ->
      {name, Regex.scan(~r/\{"([^"]+)",/, body) |> Enum.map(fn [_, v] -> v end)}
    end)
  end

  # Split on commas outside parentheses and string literals.
  defp split_args(s) do
    {parts, cur, _depth, _str} =
      s
      |> String.graphemes()
      |> Enum.reduce({[], "", 0, false}, fn
        "\"", {p, c, d, str} -> {p, c <> "\"", d, not str}
        ch, {p, c, d, true} -> {p, c <> ch, d, true}
        "(", {p, c, d, f} -> {p, c <> "(", d + 1, f}
        ")", {p, c, d, f} -> {p, c <> ")", d - 1, f}
        ",", {p, c, 0, f} -> {[String.trim(c) | p], "", 0, f}
        ch, {p, c, d, f} -> {p, c <> ch, d, f}
      end)

    Enum.reverse([String.trim(cur) | parts])
  end

  defp unquote_str("NULL"), do: ""
  defp unquote_str(s), do: s |> String.trim_leading("\"") |> String.trim_trailing("\"")

  @bounds %{
    "INT_MAX" => 2_147_483_647,
    "INT_MIN" => -2_147_483_648,
    "LONG_MAX" => 9_223_372_036_854_775_807,
    "LONG_MIN" => -9_223_372_036_854_775_808,
    "LLONG_MAX" => 9_223_372_036_854_775_807,
    "LLONG_MIN" => -9_223_372_036_854_775_808,
    "ULONG_MAX" => 18_446_744_073_709_551_615,
    "ULLONG_MAX" => 18_446_744_073_709_551_615,
    "UINT_MAX" => 4_294_967_295,
    "SIZE_MAX" => 18_446_744_073_709_551_615,
    "SSIZE_MAX" => 9_223_372_036_854_775_807,
    "LONG_MAX/2" => 4_611_686_018_427_387_903,
    "LONG_STR_SIZE" => 21,
    "CONFIG_RUN_ID_SIZE" => 40,
    "MAX_CLIENTS" => 1_000_000_000_000,
    "CONFIG_DEFAULT_MAX_CLIENTS" => 10000,
    "1024*1024" => 1_048_576
  }

  defp bound(expr) do
    e = expr |> String.replace(~r/\(\w+(\s+\w+)?\)/, "") |> String.replace(" ", "")

    cond do
      Map.has_key?(@bounds, e) -> @bounds[e]
      Regex.match?(~r/^-?\d+$/, e) -> String.to_integer(e)
      Regex.match?(~r/^(\d+)\*(\d+)$/, e) ->
        [a, b] = String.split(e, "*") |> Enum.map(&String.to_integer/1)
        a * b
      Regex.match?(~r/^(\d+)\*(\d+)\*(\d+)$/, e) ->
        e |> String.split("*") |> Enum.map(&String.to_integer/1) |> Enum.product()
      true -> raise "unknown bound #{inspect(expr)}"
    end
  end

  defp config(kind, a, enums, defaults) do
    name = unquote_str(Enum.at(a, 0))
    alias_name = unquote_str(Enum.at(a, 1))
    flags = Enum.at(a, 2)
    has = fn f -> String.contains?(flags, f) end

    rust_kind =
      case kind do
        "Bool" ->
          "ConfigKind::Bool"

        k when k in ~w(String SDS) ->
          "ConfigKind::Str"

        "Enum" ->
          choices = Map.fetch!(enums, Enum.at(a, 3))
          "ConfigKind::Enum { choices: #{strs(choices)}, multi: #{has.("MULTI_ARG_CONFIG")} }"

        "Special" ->
          "ConfigKind::Special"

        _numeric ->
          # name, alias, flags, lower, upper, addr, default, num_conf_flags, ...
          numflags = Enum.at(a, 7)

          "ConfigKind::Int { min: #{bound(Enum.at(a, 3))}, max: #{bound(Enum.at(a, 4))}, " <>
            "memory: #{String.contains?(numflags, "MEMORY_CONFIG")}, " <>
            "percent: #{String.contains?(numflags, "PERCENT_CONFIG")}, " <>
            "octal: #{String.contains?(numflags, "OCTAL_CONFIG")} }"
      end

    """
        ConfigSpec {
            name: #{s(name)},
            alias: #{s(alias_name)},
            immutable: #{has.("IMMUTABLE_CONFIG")},
            hidden: #{has.("HIDDEN_CONFIG")},
            protected: #{has.("PROTECTED_CONFIG")},
            kind: #{rust_kind},
            default: #{s(Map.get(defaults, name, ""))},
        },
    """
  end

  # ──────────────────────────────── helpers ───────────────────────────────

  defp s(str), do: inspect(str || "", printable_limit: :infinity) |> rust_escape()

  # Elixir's inspect is close to a Rust literal; Rust has no \e or #{.
  defp rust_escape(lit), do: lit |> String.replace("\\e", "\\x1b") |> String.replace("\\#", "#")

  defp strs(list), do: "&[" <> Enum.map_join(list, ", ", &s/1) <> "]"
end

Gen.run(System.argv())
